/**
 * Traduction anglaise. L'interface est écrite en français ; chaque texte affiché est traduit
 * morceau par morceau (les plus longs d'abord), ce qui gère aussi les textes avec des valeurs
 * variables (« Risque : 45/100 » → « Risk: 45/100 »). Un morceau absent reste en français.
 */
object I18n {
    @Volatile var english = false
        private set

    /** Étiquette d'une vue à ne jamais traduire (texte d'un SMS, adresse d'un lien…). */
    const val NO_TR = "no-translate"

    fun init(c: Context) {
        english = when (Store.lang(c)) {
            "en" -> true
            "fr" -> false
            else -> Locale.getDefault().language != "fr"
        }
    }

    /** Retire un éventuel emoji / symbole en tête (« ✅ Texte » → « Texte »). */
    private fun stripLead(s: String) = s.dropWhile { !it.isLetterOrDigit() && it !in "«(\"'+-.[" }

    private val pairs: List<Pair<String, String>> by lazy {
        // Chaque entrée existe aussi sans son emoji de tête (les écrans utilisent maintenant des icônes)
        val extra = DICT.mapNotNull { (fr, en) ->
            val f = stripLead(fr)
            if (f != fr && f.length >= 4) f to stripLead(en) else null
        }
        (DICT + extra).distinctBy { it.first }.sortedByDescending { it.first.length }
    }

    fun tr(s: CharSequence): String {
        var out = s.toString()
        if (!english || out.isEmpty()) return out
        for ((fr, en) in pairs) if (out.contains(fr)) out = out.replace(fr, en)
        return out
    }

    /** Traduit tous les textes visibles d'un écran (jamais ce que l'utilisateur a tapé). */
    fun translateTree(v: View) {
        if (!english || v.tag == NO_TR) return
        when (v) {
            is EditText -> v.hint?.let { h -> val t = tr(h); if (t != h.toString()) v.hint = t }
            is TextView -> {
                val cur = v.text
                if (cur.isNotEmpty()) {
                    val t = tr(cur)
                    if (t != cur.toString()) v.text = t
                }
                v.hint?.let { h -> val t = tr(h); if (t != h.toString()) v.hint = t }
            }
            is ViewGroup -> for (i in 0 until v.childCount) translateTree(v.getChildAt(i))
        }
    }

